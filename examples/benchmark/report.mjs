// Turns a results file from run.mjs into docs/BENCHMARK.md and a shields.io endpoint at docs/benchmark.json.
// Usage: node benchmark/report.mjs [results/latest.json] [--docs ../docs]
import { parseArgs } from "node:util";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const fmt = (n) => Math.round(n).toLocaleString("en-US");
const pct = (withTokens, without) => (without > 0 ? `${Math.round((1 - withTokens / without) * 100)}%` : "n/a");
const secs = (ms) => (ms == null ? "n/a" : `${(ms / 1000).toFixed(1)}s`);
const median = (xs) => {
  if (xs.length === 0) return null;
  const s = xs.slice().sort((a, b) => a - b);
  const mid = Math.floor(s.length / 2);
  return s.length % 2 ? s[mid] : (s[mid - 1] + s[mid]) / 2;
};
const sum = (xs, f) => xs.reduce((n, x) => n + f(x), 0);
const table = (header, rows) => [`| ${header.join(" | ")} |`, `| ${header.map(() => "---").join(" | ")} |`, ...rows.map((r) => `| ${r.join(" | ")} |`)].join("\n");

/**
 * Pairs each codemcp run with the direct run of the same (set, task, model, repeat). Only pairs where
 * both sides completed without a transport or provider error count towards token figures, so a
 * timeout on one side never shows up as a saving on the other. Pass rates use every run.
 */
function pairs(runs) {
  const by = new Map();
  for (const r of runs) {
    const key = `${r.set}\0${r.task}\0${r.model}\0${r.repeat}`;
    if (!by.has(key)) by.set(key, {});
    by.get(key)[r.mode] = r;
  }
  return [...by.values()].filter((p) => p.codemcp && p.direct && !p.codemcp.error && !p.direct.error);
}

function summarize(withRuns, withoutRuns, paired) {
  const tokens = (r) => r.inputTokens + r.outputTokens;
  const withTokens = sum(paired, (p) => tokens(p.codemcp));
  const withoutTokens = sum(paired, (p) => tokens(p.direct));
  const withFirst = sum(paired, (p) => p.codemcp.firstInputTokens);
  const withoutFirst = sum(paired, (p) => p.direct.firstInputTokens);
  const rate = (rs) => (rs.length ? `${rs.filter((r) => r.pass).length}/${rs.length}` : "n/a");
  return {
    paired: paired.length,
    withTokens,
    withoutTokens,
    saving: pct(withTokens, withoutTokens),
    firstSaving: pct(withFirst, withoutFirst),
    passWith: rate(withRuns),
    passWithout: rate(withoutRuns),
    timeWith: median(withRuns.filter((r) => !r.error).map((r) => r.wallMs)),
    timeWithout: median(withoutRuns.filter((r) => !r.error).map((r) => r.wallMs)),
  };
}

/** Headline saving across every model in a set, as a fraction, or null when nothing paired. */
export function headlineSaving(results, setName) {
  const p = pairs(results.runs.filter((r) => r.set === setName));
  if (p.length === 0) return null;
  const tokens = (r) => r.inputTokens + r.outputTokens;
  const without = sum(p, (x) => tokens(x.direct));
  return without > 0 ? 1 - sum(p, (x) => tokens(x.codemcp)) / without : null;
}

export function renderMarkdown(results) {
  const out = [];
  out.push("# Benchmark: codemcp against the same servers attached directly");
  out.push("");
  out.push("Generated by `examples/benchmark/run.mjs`; do not edit by hand. Each task runs twice per model and repeat: once with codemcp's three tools (`search`, `describe`, `execute`) and once with every upstream tool definition passed to the provider as `server__tool` and calls made straight to the servers. Token counts are the providers' own `usage` figures with no prompt caching. A run passes when the final answer matches every regex in `tasks.json`.");
  out.push("");
  out.push(`- Date: ${results.date}`);
  out.push(`- Models: ${results.models.map((m) => `\`${m.id}\``).join(", ")}${results.skippedModels?.length ? ` (skipped: ${results.skippedModels.map((m) => `\`${m.id}\``).join(", ")})` : ""}`);
  out.push(`- Repeats per task and model: ${results.repeats}`);
  out.push(`- Command: \`${results.command}\` (Node ${results.node}, ${results.platform})`);
  if (results.skippedSets?.length) out.push(`- Skipped server sets: ${results.skippedSets.map((s) => `\`${s.name}\` (${s.missing.join(", ")} unset)`).join(", ")}`);
  out.push("");

  for (const set of results.sets) {
    const runs = results.runs.filter((r) => r.set === set.name);
    const paired = pairs(runs);
    out.push(`## Server set \`${set.name}\``);
    out.push("");
    out.push(`${set.description ? `${set.description} ` : ""}${set.totalTools} tools across ${set.servers.length} servers, about ${fmt(set.totalDefinitionTokens)} tokens of tool definitions when attached directly, against about ${fmt(set.proxyDefinitionTokens)} for codemcp's ${set.proxyTools} tools.`);
    out.push("");
    out.push("### Headline");
    out.push("");
    const rows = results.models.map(({ id }) => {
      const mine = runs.filter((r) => r.model === id);
      const s = summarize(mine.filter((r) => r.mode === "codemcp"), mine.filter((r) => r.mode === "direct"), paired.filter((p) => p.codemcp.model === id));
      return [`\`${id}\``, s.paired, fmt(s.withTokens), fmt(s.withoutTokens), s.saving, s.firstSaving, s.passWith, s.passWithout, secs(s.timeWith), secs(s.timeWithout)];
    });
    const all = summarize(runs.filter((r) => r.mode === "codemcp"), runs.filter((r) => r.mode === "direct"), paired);
    if (results.models.length > 1) rows.push(["**all**", all.paired, fmt(all.withTokens), fmt(all.withoutTokens), all.saving, all.firstSaving, all.passWith, all.passWithout, secs(all.timeWith), secs(all.timeWithout)]);
    out.push(table(["Model", "Paired runs", "Tokens with codemcp", "Tokens direct", "Saving", "First-request saving", "Pass with codemcp", "Pass direct", "Median time with", "Median time direct"], rows));
    out.push("");
    out.push("Tokens are input plus output summed over paired runs (both modes finished without a transport error). First-request saving compares the input tokens of the first model call, where the tool definitions are paid for. Pass counts include every run.");
    out.push("");

    out.push("### Servers ranked by definition cost");
    out.push("");
    out.push("What each server adds to every request when attached directly, estimated at four characters per token over the JSON the provider receives.");
    out.push("");
    const ranked = set.servers.slice().sort((a, b) => b.definitionTokens - a.definitionTokens);
    out.push(
      table(
        ["Rank", "Server", "State", "Tools", "Definition tokens", "Share"],
        ranked.map((s, i) => [i + 1, `\`${s.name}\``, s.state, s.tools, fmt(s.definitionTokens), set.totalDefinitionTokens ? `${Math.round((s.definitionTokens / set.totalDefinitionTokens) * 100)}%` : "n/a"]),
      ),
    );
    out.push("");

    out.push("### Per task");
    out.push("");
    const taskRows = [];
    for (const task of results.tasks) {
      for (const { id } of results.models) {
        const mine = runs.filter((r) => r.task === task.id && r.model === id);
        if (mine.length === 0) continue;
        const s = summarize(mine.filter((r) => r.mode === "codemcp"), mine.filter((r) => r.mode === "direct"), paired.filter((p) => p.codemcp.task === task.id && p.codemcp.model === id));
        const calls = (mode) => {
          const rs = mine.filter((r) => r.mode === mode && !r.error);
          return rs.length ? (sum(rs, (r) => r.toolCalls) / rs.length).toFixed(1) : "n/a";
        };
        taskRows.push([`\`${task.id}\``, `\`${id}\``, fmt(s.withTokens), fmt(s.withoutTokens), s.saving, s.passWith, s.passWithout, calls("codemcp"), calls("direct")]);
      }
    }
    out.push(table(["Task", "Model", "Tokens with", "Tokens direct", "Saving", "Pass with", "Pass direct", "Tool calls with", "Tool calls direct"], taskRows));
    out.push("");
    const errors = runs.filter((r) => r.error);
    if (errors.length) {
      out.push("### Errors");
      out.push("");
      out.push(table(["Task", "Model", "Mode", "Repeat", "Error"], errors.map((r) => [`\`${r.task}\``, `\`${r.model}\``, r.mode, r.repeat, r.error.replace(/\|/g, "\\|").replace(/\s+/g, " ").slice(0, 160)])));
      out.push("");
    }
  }

  out.push("## Tasks");
  out.push("");
  out.push(table(["Id", "Servers", "Question"], results.tasks.map((t) => [`\`${t.id}\``, (t.servers ?? []).map((s) => `\`${s}\``).join(", "), t.question.replace(/\|/g, "\\|")])));
  out.push("");
  out.push("## Reproduce");
  out.push("");
  out.push("```bash");
  out.push("pnpm install && pnpm build");
  out.push(`pnpm --filter codemcp-examples benchmark -- --set ${results.sets.map((s) => s.name).join(",")} --repeats ${results.repeats} --models ${results.models.map((m) => m.id).join(",")}`);
  out.push("```");
  out.push("");
  out.push("Set `ANTHROPIC_API_KEY` and `OPENAI_API_KEY` for the providers you want; a model whose key is missing is skipped. The `with-keys` set also needs the variables named in `examples/benchmark/servers.json`. The direct side bypasses codemcp's policy, approvals, pinning and audit; it exists only to measure the difference.");
  out.push("");
  return out.join("\n");
}

/** shields.io endpoint badge: https://shields.io/badges/endpoint-badge */
export function renderBadge(results) {
  const set = results.sets.find((s) => s.name === "no-key") ?? results.sets[0];
  const saving = set ? headlineSaving(results, set.name) : null;
  if (saving == null) return { schemaVersion: 1, label: "tokens vs direct MCP", message: "not measured", color: "lightgrey" };
  const p = Math.round(saving * 100);
  return { schemaVersion: 1, label: "tokens vs direct MCP", message: `${p >= 0 ? "-" : "+"}${Math.abs(p)}%`, color: p >= 50 ? "brightgreen" : p >= 20 ? "green" : p > 0 ? "yellow" : "red" };
}

/** Writes BENCHMARK.md and benchmark.json into `docsDir` and returns the paths. */
export async function writeReport(results, docsDir) {
  await mkdir(docsDir, { recursive: true });
  const md = resolve(docsDir, "BENCHMARK.md");
  const badge = resolve(docsDir, "benchmark.json");
  await writeFile(md, renderMarkdown(results));
  await writeFile(badge, `${JSON.stringify(renderBadge(results), null, 2)}\n`);
  return [md, badge];
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const here = fileURLToPath(new URL("./", import.meta.url));
  const { values, positionals } = parseArgs({ allowPositionals: true, options: { docs: { type: "string", default: resolve(here, "../../docs") } } });
  const file = resolve(positionals[0] ?? resolve(here, "results/latest.json"));
  const results = JSON.parse(await readFile(file, "utf8"));
  const written = await writeReport(results, values.docs);
  console.error(`[benchmark] wrote ${written.join(", ")}`);
}
